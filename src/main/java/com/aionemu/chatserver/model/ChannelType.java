package com.aionemu.chatserver.model;

/**
 * 聊天频道类型枚举。
 * Chat channel type enumeration.
 *
 * @author ATracer
 */
public enum ChannelType {

    /**
     * 公共区域频道 / Public region channel
     */
    PUBLIC,
    /**
     * 交易频道 / Trade channel
     */
    TRADE,
    /**
     * 组队招募频道 / Looking-for-group channel
     */
    GROUP,
    /**
     * 职业频道 / Job class channel
     */
    JOB,
    /**
     * 语言频道 / Language channel
     */
    LANG;
}
