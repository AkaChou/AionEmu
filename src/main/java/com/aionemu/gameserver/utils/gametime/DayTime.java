package com.aionemu.gameserver.utils.gametime;

/**
 * 游戏内时段枚举（晨/午/晚/夜）。
 * In-game day-time period enum (morning/afternoon/evening/night).
 *
 * @author ATracer
 */
public enum DayTime {
	/**
	 * 早晨。
	 * Morning.
	 */
	MORNING,
	/**
	 * 下午。
	 * Afternoon.
	 */
	AFTERNOON,
	/**
	 * 傍晚。
	 * Evening.
	 */
	EVENING,
	/**
	 * 夜晚。
	 * Night.
	 */
	NIGHT
}
